package gen

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"reflect"
	"slices"
	"strings"

	"github.com/chucklehead-dev/gotogether/grist/internal/catalog"
	"github.com/chucklehead-dev/gotogether/grist/internal/rec"
)

// LockFile is the catalog's record of what has been stored (beside the
// app, checked in): every version of every event type with its shape,
// and every read model's version and fingerprint. Generate writes it and
// refuses a version whose shape changed since: the stored events of that
// version would decode into the new struct silently.
const LockFile = "grist.lock"

// A lockFile is grist.lock's content.
type lockFile struct {
	Note       string          `json:"note"`
	Events     []lockEvent     `json:"events"`
	ReadModels []lockReadModel `json:"readModels"`
}

// lockNote is grist.lock's note: what it is, for a reader of the file.
const lockNote = "Generated by grist model: every version of every event type the app has stored, by shape (its fields' JSON names and schema types, its tags), and every read model's fingerprint (its snapshots'). A version's shape never changes: a changed struct is a new version with an upcaster (docs/grist.md §2.1). Check it in; delete a version's entry only if no event of it was ever stored."

type lockEvent struct {
	Name     string        `json:"name"`
	Versions []lockVersion `json:"versions"`
}

type lockVersion struct {
	Version int      `json:"version"`
	Shape   string   `json:"shape"`  // a hash of the fields' schema and the tags
	Fields  []string `json:"fields"` // "name type", " tag" after a tag, in field order: for a reader
}

type lockReadModel struct {
	Name        string `json:"name"`
	Version     int    `json:"version"`
	Fingerprint string `json:"fingerprint"`
}

// shapeOf is the lock's version of a struct with tags.
func shapeOf(version int, body reflect.Type, tags []string) lockVersion {
	b, _ := json.Marshal(struct {
		Body map[string]any `json:"body"`
		Tags []string       `json:"tags"`
	}{catalog.Schema(body), catalog.NonNil(tags)})
	h := sha256.Sum256(b)
	v := lockVersion{Version: version, Shape: hex.EncodeToString(h[:])[:16], Fields: []string{}}
	props, _ := catalog.Schema(body)["properties"].(map[string]any)
	for i := 0; body != nil && body.Kind() == reflect.Struct && i < body.NumField(); i++ {
		f := body.Field(i)
		name := rec.JSONName(f)
		if !f.IsExported() || name == "-" {
			continue
		}
		typ := "?"
		if p, ok := props[name].(map[string]any); ok {
			switch t := p["type"].(type) {
			case string:
				typ = t
			case []string:
				typ = strings.Join(t, "|")
			case []any:
				var ts []string
				for _, x := range t {
					ts = append(ts, fmt.Sprint(x))
				}
				typ = strings.Join(ts, "|")
			}
		}
		field := name + " " + typ
		if slices.Contains(tags, name) {
			field += " tag"
		}
		v.Fields = append(v.Fields, field)
	}
	return v
}

// lockOf is the lock the catalog makes, from the one before (prev, nil
// if none): every event's versions (an event the app no longer registers
// kept, as its stored events are), every read model's fingerprint. It
// returns why the catalog contradicts prev (a version whose shape
// changed, a version newer than the app's), and warnings: an event kept
// that the app no longer registers, a read model whose fingerprint
// changed at the same version.
func lockOf(c Catalog, prev []byte) (lock []byte, errs, warnings []string) {
	var old lockFile
	if prev != nil {
		if err := json.Unmarshal(prev, &old); err != nil {
			return nil, []string{fmt.Sprintf("%s is not one grist wrote (%v): restore it from version control", LockFile, err)}, nil
		}
	}
	oldEvents := map[string]lockEvent{}
	for _, e := range old.Events {
		oldEvents[e.Name] = e
	}
	next := lockFile{Note: lockNote, Events: []lockEvent{}, ReadModels: []lockReadModel{}}
	registered := map[string]bool{}
	for _, e := range c.Events {
		if strings.HasPrefix(e.Name, "grist.") {
			continue // grist's own (grist.failed, grist.unknown): its versions are grist's
		}
		registered[e.Name] = true
		le := lockEvent{Name: e.Name}
		for _, o := range e.Older {
			le.Versions = append(le.Versions, shapeOf(o.Version, o.Body, o.Tags))
		}
		le.Versions = append(le.Versions, shapeOf(e.Version, e.Body, e.Tags))
		was := oldEvents[e.Name]
		for _, ov := range was.Versions {
			if ov.Version < 1 {
				continue
			}
			if ov.Version > e.Version {
				errs = append(errs, fmt.Sprintf("event %s: %s records version %d, and the app's newest is %d: a newer version of the app stored it; "+
					"this one would refuse its events (grist.NewerVersionError). Build from the newer version, or, if no event of version %d was ever stored, delete its entry from %s",
					e.Name, LockFile, ov.Version, e.Version, ov.Version, LockFile))
				continue
			}
			nv := le.Versions[ov.Version-1]
			if ov.Shape == nv.Shape {
				continue
			}
			goName := "Event"
			if e.Body != nil && e.Body.Name() != "" {
				goName = e.Body.Name()
			}
			errs = append(errs, fmt.Sprintf("event %s version %d changed shape since %s was written (fields [%s], then [%s]): its stored events would decode into the new struct silently (a renamed field reads as its zero value). "+
				"Keep the old struct (%sV%d), and register the new shape as version %d with an upcaster from it: grist.NewEvent[%s](App, %q, grist.Upcast(%d, func(v %sV%d) %s { ... })), or Upcast's chain extended by one. "+
				"If no event of version %d was ever stored (it was never deployed), delete its entry from %s",
				e.Name, ov.Version, LockFile, strings.Join(ov.Fields, ", "), strings.Join(nv.Fields, ", "),
				goName, ov.Version, e.Version+1, goName, e.Name, e.Version, goName, e.Version, goName, ov.Version, LockFile))
		}
		next.Events = append(next.Events, le)
	}
	for _, e := range old.Events {
		if !registered[e.Name] {
			next.Events = append(next.Events, e)
			warnings = append(warnings, fmt.Sprintf("event %s is in %s and the app registers it no more: its stored events are never read (kept in %s, as they are in the store)", e.Name, LockFile, LockFile))
		}
	}
	oldRMs := map[string]lockReadModel{}
	for _, rm := range old.ReadModels {
		oldRMs[rm.Name] = rm
	}
	for _, rm := range c.ReadModels {
		next.ReadModels = append(next.ReadModels, lockReadModel{Name: rm.Name, Version: rm.Version, Fingerprint: rm.Fingerprint})
		if was, ok := oldRMs[rm.Name]; ok && was.Version == rm.Version && was.Fingerprint != rm.Fingerprint {
			warnings = append(warnings, fmt.Sprintf("read model %s folds otherwise than when %s was written (its fingerprint changed: an event it folds changed shape or version, or its fold makes something else of the same events), at the same version %d: "+
				"the snapshots the deployed version took are another fold's, never read, so its reads fold from the start of the log until they take their own. If what the fold means changed, bump its version: a change of meaning no generated event shows keeps the fingerprint",
				rm.Name, LockFile, rm.Version))
		}
	}
	b, _ := json.MarshalIndent(next, "", "  ")
	return append(b, '\n'), errs, warnings
}
