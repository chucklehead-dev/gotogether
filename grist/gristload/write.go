package gristload

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// YAML is the sizing as sizing.yaml: a header saying what produced it,
// what was measured, each setting under its key's path (gateway:
// retries: POST:) with its value, because, formula, tool, margin, caveat
// and evidence, and the findings. A manifest generator reads it only
// when asked (`<app> manifests -sizing`, docs/grist-platform.md decision
// 5): a recommendation never enters a manifest silently.
func (s *Sizing) YAML(command string) ([]byte, error) {
	root := &yaml.Node{Kind: yaml.MappingNode}
	l := s.Load
	root.HeadComment = fmt.Sprintf("generated by `%s` from %d steps (%d client calls; the busiest tenant %s, %.0f%% of them; at most %d in flight at once)\n"+
		"load: %g/s, burst %v, recovery within %v at probability %g; in force: gateway %d × client %d on commands, per-try timeout %v\n"+
		"every value with its formula, tool, margin and caveat: the chain (qmeta) ranks, the simulation (qload) confirms, never a bare chain number (docs/grist-platform.md §8.5)",
		command, s.Measured.Steps, s.Measured.Calls, s.Measured.Hot, 100*s.Measured.HotShare, s.Measured.InFlight,
		l.Rate, l.Burst, l.Within, l.Prob, l.Gateway.Commands, attempts(l.Client), l.Timeout)
	measured := &yaml.Node{Kind: yaml.MappingNode}
	for _, n := range s.Measured.Order() {
		b := s.Measured.Blocks[n]
		sv := b.Service
		m := &yaml.Node{Kind: yaml.MappingNode, Style: yaml.FlowStyle}
		put(m, "kind", string(b.Kind))
		put(m, "calls", fmt.Sprint(len(sv.Samples)))
		put(m, "mean", round(sv.Mean).String())
		put(m, "p50", round(sv.Quantile(0.5)).String())
		put(m, "p99", round(sv.Quantile(0.99)).String())
		put(m, "p999", round(sv.Quantile(0.999)).String())
		put(m, "cv", fmt.Sprintf("%.2f", sv.CV))
		put(m, "exponential", fmt.Sprint(sv.Exponential()))
		set(measured, b.Name, m)
	}
	set(root, "measured", measured)
	for _, st := range s.Settings {
		parent := root
		parts := strings.Split(st.Key, ".")
		for _, p := range parts[:len(parts)-1] {
			parent = child(parent, p)
		}
		v := &yaml.Node{Kind: yaml.MappingNode}
		val := &yaml.Node{}
		if err := val.Encode(st.Value); err != nil {
			return nil, err
		}
		set(v, "value", val)
		for _, f := range []struct{ k, v string }{{"because", st.Because}, {"formula", st.Formula}, {"tool", st.Tool},
			{"margin", st.Margin}, {"inForce", st.InForce}, {"caveat", st.Caveat}, {"evidence", st.Evidence}} {
			if f.v != "" {
				put(v, f.k, f.v)
			}
		}
		set(parent, parts[len(parts)-1], v)
	}
	findings := &yaml.Node{Kind: yaml.SequenceNode}
	for _, f := range s.Findings {
		findings.Content = append(findings.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: f})
	}
	set(root, "findings", findings)
	var b bytes.Buffer
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(&yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{root}}); err != nil {
		return nil, err
	}
	return b.Bytes(), enc.Close()
}

func put(m *yaml.Node, k, v string) {
	set(m, k, &yaml.Node{Kind: yaml.ScalarNode, Value: v})
}

func set(m *yaml.Node, k string, v *yaml.Node) {
	m.Content = append(m.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: k}, v)
}

// child is m's mapping under k, made if absent.
func child(m *yaml.Node, k string) *yaml.Node {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == k {
			return m.Content[i+1]
		}
	}
	c := &yaml.Node{Kind: yaml.MappingNode}
	set(m, k, c)
	return c
}

// Write writes the sizing to path (deploy/sizing.yaml) and its evidence
// beside it (deploy/sizing/*.svg), command naming what produced it in
// the header.
func (s *Sizing) Write(path, command string) error {
	b, err := s.YAML(command)
	if err != nil {
		return err
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, data := range s.Evidence {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, data, 0o644); err != nil {
			return err
		}
	}
	return os.WriteFile(path, b, 0o644)
}

// Text is the settings as lines for a terminal: key, value, because.
func (s *Sizing) Text() string {
	var b strings.Builder
	for _, st := range s.Settings {
		fmt.Fprintf(&b, "%s: %v\n  because %s\n  tool: %s", st.Key, st.Value, st.Because, st.Tool)
		if st.Margin != "" {
			fmt.Fprintf(&b, "; margin: %s", st.Margin)
		}
		if st.InForce != "" {
			fmt.Fprintf(&b, "\n  in force: %s", st.InForce)
		}
		b.WriteString("\n")
	}
	for _, f := range s.Findings {
		fmt.Fprintf(&b, "finding: %s\n", f)
	}
	return b.String()
}
