// The checked-in shoptypes/shop_types.go is what its model generates now
// (the golden: copied with the model, at the same relative path, -check
// passes); after the model's types change, -check fails (exit 1) naming
// each type that changed and the command that writes the file again,
// which then writes it; a file edited by hand is stale even when no type
// changed; a missing one is reported before quint runs.
func TestTypesCheck(t *testing.T) {
	skip.Quint(t)
	dir := t.TempDir()
	model, err := os.ReadFile("../../internal/typegen/testdata/shop.qnt")
	if err != nil {
		t.Fatal(err)
	}
	golden, err := os.ReadFile("../../internal/typegen/shoptypes/shop_types.go")
	if err != nil {
		t.Fatal(err)
	}
	spec, gen := filepath.Join(dir, "testdata", "shop.qnt"), filepath.Join(dir, "shoptypes", "shop_types.go")
	for path, src := range map[string][]byte{spec: model, gen: golden} {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, src, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	args := []string{"-spec", spec, "-main", "shop", "-package", "shoptypes", "-o", gen}
	var out bytes.Buffer
	if code, err := types(t.Context(), &out, append([]string{"-check"}, args...)); code != 0 || err != nil || !strings.Contains(out.String(), "ok   "+gen+": current for ../testdata/shop.qnt (module shop: 9 types and State of 9 variables)") {
		t.Fatalf("the checked-in file: %d, %v\n%s(write it again: go generate ./internal/typegen/shoptypes)", code, err, out.String())
	}
	changed := strings.Replace(string(model), "type Phase = Idle | Open | Closed", "type Phase = Idle | Open | Closed | Archived\n  type Note = str", 1)
	if err := os.WriteFile(spec, []byte(changed), 0o600); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	fix := "run gotogether types -spec " + spec + " -main shop -package shoptypes -o " + gen
	if code, err := types(t.Context(), &out, append([]string{"-check"}, args...)); code != 1 || err != nil || !strings.Contains(out.String(), "FAIL "+gen+": stale: type Note added, type Phase changed: "+fix+"\n") {
		t.Fatalf("stale: %d, %v\n%s", code, err, out.String())
	}
	out.Reset()
	if code, err := types(t.Context(), &out, args); code != 0 || err != nil || !strings.Contains(out.String(), "written from ../testdata/shop.qnt (module shop: 10 types") {
		t.Fatalf("write: %d, %v\n%s", code, err, out.String())
	}
	if src, _ := os.ReadFile(gen); !strings.Contains(string(src), `PhaseArchived Phase = "Archived"`) || !strings.Contains(string(src), "type Note = string") {
		t.Errorf("the written file has no Archived or Note:\n%s", src)
	}
	// by hand: the types are the model's, the file is not the generator's
	src, _ := os.ReadFile(gen)
	if err := os.WriteFile(gen, bytes.Replace(src, []byte("type Note = string"), []byte("type Note = []byte"), 1), 0o600); err != nil {
		t.Fatal(err)
	}
	out.Reset()
	if code, err := types(t.Context(), &out, append([]string{"-check"}, args...)); code != 1 || err != nil || !strings.Contains(out.String(), "stale: the model's types are as they were, but the file is not what this gotogether generates") {
		t.Fatalf("edited: %d, %v\n%s", code, err, out.String())
	}
	out.Reset()
	missing := filepath.Join(dir, "none", "types.go")
	if code, err := types(t.Context(), &out, []string{"-check", "-spec", spec, "-o", missing}); code != 1 || err != nil || !strings.Contains(out.String(), "FAIL "+missing+": missing: run gotogether types -spec "+spec+" -o "+missing) {
		t.Fatalf("missing: %d, %v\n%s", code, err, out.String())
	}
}

// -binding takes the spec and module from a binding (here a literate
// model's, its .md tangled first), and with no -o the file goes to
// standard output in package model.
func TestTypesFromABinding(t *testing.T) {
	skip.Quint(t)
	var out bytes.Buffer
	code, err := types(t.Context(), &out, []string{"-binding", "../../validate/testdata/literate/counter.binding.yaml"})
	if code != 0 || err != nil {
		t.Fatalf("%d, %v\n%s", code, err, out.String())
	}
	for _, want := range []string{"// Code generated by gotogether types from ../../validate/testdata/literate/counter.md (module counter); DO NOT EDIT.", "package model\n", "N int `itf:\"n\"`"} {
		if !strings.Contains(out.String(), want) {
			t.Errorf("no %q in:\n%s", want, out.String())
		}
	}
}

// A bad invocation exits 2 and says what to give, before quint runs.
func TestTypesFlags(t *testing.T) {
	for _, c := range []struct {
		args []string
		want string
	}{
		{nil, "types needs -spec model.qnt -main M, or -binding b.yaml: gotogether types -spec"},
		{[]string{"-spec", "m.qnt", "extra"}, "types takes no arguments (extra)"},
		{[]string{"-binding", "b.yaml", "-spec", "m.qnt"}, "-binding names the spec and its module"},
		{[]string{"-spec", "m.qnt", "-check"}, "types -check compares a file: name it with -o"},
		{[]string{"-spec", "m.qnt", "-package", "type"}, `-package "type" is a Go keyword`},
		{[]string{"-spec", "m.qnt", "-package", "my-types"}, `-package "my-types" is no Go package name`},
		{[]string{"-nope"}, "types: flag provided but not defined: -nope (gotogether types -h lists its flags)"},
		{[]string{"-spec", "nowhere.qnt"}, "the spec nowhere.qnt does not exist"},
	} {
		var out bytes.Buffer
		code, err := types(t.Context(), &out, c.args)
		if code != 2 || err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("types %v: %d, %v; want exit 2 and %q", c.args, code, err, c.want)
		}
	}
	var out bytes.Buffer
	if code, err := types(t.Context(), &out, []string{"-h"}); code != 0 || err != nil || !strings.Contains(out.String(), commands["types"].purpose) || !strings.Contains(out.String(), "-check") {
		t.Errorf("-h: %d, %v\n%s", code, err, out.String())
	}
}
