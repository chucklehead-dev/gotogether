// An EvalModule is a Quint module through which a model is evaluated in
// Go (internal/qeval) instead of replayed by quint: it imports the model
// with its constants passed through (one compilation serves every
// instance), and holds a definition for each action's expect whose
// parameters are the template's fields. A step is then the model's
// action applied to its call's arguments, and its expect the definition
// applied to the call's ExpectArgs: the same Quint, with the step's
// values in place of the template's fields.
type EvalModule struct {
	Name string // the module's
	Text string // its source
	Init string // its init action (the model's)
	// Consts are the model's constants the binding computes from the steps,
	// each the name of the module's own that passes it through (the others
	// are written in the import)
	Consts map[string]string
	// Actions are the model's actions, each the name of the module's that
	// applies it; Expects each action's expect, its definition's name
	Actions, Expects map[string]string
	// Invariants and Eventually are the binding's vals, each the name of
	// the module's val that reads it; Vals every val a Within names
	Invariants, Eventually, Vals map[string]string
}

// evalPrefix names what the module adds, apart from the model's names.
const evalPrefix = "__gtg_"

// EvalModule is the binding's evaluation module, written for qntPath (the
// model's import is relative to it). A binding whose templates the module
// cannot carry (a template that is more than text and fields, a constant
// whose type the model does not say) has none: the error says why.
func (b *Binding) EvalModule(m *Model, qntPath string) (*EvalModule, error) {
	em := &EvalModule{Name: evalPrefix + "eval", Init: evalPrefix + "init", Consts: map[string]string{},
		Expects: map[string]string{}, Invariants: map[string]string{}, Eventually: map[string]string{}, Vals: map[string]string{}}
	var w strings.Builder
	fmt.Fprintf(&w, "// Generated by gotogether for the Go evaluator: %s's model, its constants passed through.\n", filepath.Base(b.SpecPath()))
	fmt.Fprintf(&w, "module %s {\n", em.Name)
	// a constant the binding gives as Quint is the module's own; one it
	// computes from the steps (set, max, count) is passed through, its
	// value per instance a literal
	var overrides []string
	for _, c := range sortedKeys(m.Consts) {
		if tpl, ok := b.Constants[c]; ok && !strings.Contains(tpl, "{{") {
			overrides = append(overrides, c+" = "+tpl)
			continue
		}
		name := evalPrefix + "c_" + c
		fmt.Fprintf(&w, "  const %s: %s\n", name, m.Consts[c])
		em.Consts[c] = name
		overrides = append(overrides, c+" = "+name)
	}
	rel, err := filepath.Rel(filepath.Dir(qntPath), b.SpecPath())
	if err != nil {
		return nil, err
	}
	rel = strings.TrimSuffix(filepath.ToSlash(rel), ".qnt")
	if len(overrides) > 0 {
		fmt.Fprintf(&w, "  import %s(%s).* from %q\n", b.Module, strings.Join(overrides, ", "), rel)
	} else {
		fmt.Fprintf(&w, "  import %s.* from %q\n", b.Module, rel)
	}
	if b.Defs != "" {
		w.WriteString(b.Defs + "\n")
	}
	for _, a := range sortedKeys(b.Actions) {
		ab := b.Actions[a]
		if ab.Expect == "" {
			continue
		}
		parts, holes, err := splitTemplate(ab.Expect)
		if err != nil {
			return nil, fmt.Errorf("action %s's expect: %w", a, err)
		}
		name := evalPrefix + "expect_" + a
		params := make([]string, len(holes))
		var body strings.Builder
		for i := range holes {
			params[i] = fmt.Sprintf("%sh%d", evalPrefix, i)
			body.WriteString(parts[i] + params[i])
		}
		body.WriteString(parts[len(holes)])
		sig := ""
		if len(params) > 0 {
			sig = "(" + strings.Join(params, ", ") + ")"
		}
		fmt.Fprintf(&w, "  def %s%s = %s\n", name, sig, body.String())
		em.Expects[a] = name
	}
	for i, inv := range b.Invariants {
		name := fmt.Sprintf("%sinv_%d", evalPrefix, i)
		fmt.Fprintf(&w, "  val %s = %s\n", name, inv)
		em.Invariants[inv] = name
	}
	for i, ev := range b.Eventually {
		name := fmt.Sprintf("%sev_%d", evalPrefix, i)
		fmt.Fprintf(&w, "  val %s = %s\n", name, ev)
		em.Eventually[ev] = name
	}
	for _, rule := range b.Within {
		for _, v := range []string{rule.After, rule.Holds} {
			if _, ok := em.Vals[v]; !ok {
				name := fmt.Sprintf("%sval_%d", evalPrefix, len(em.Vals))
				fmt.Fprintf(&w, "  val %s = %s\n", name, v)
				em.Vals[v] = name
			}
		}
	}
	fmt.Fprintf(&w, "  action %s = init\n", em.Init)
	// each action through a definition of the module's own: quint keeps
	// those, and what they reach, where it drops what init and step do not
	acts := sortedKeys(m.Actions)
	if _, ok := m.Actions[b.Restart]; b.Restart != "" && !ok {
		acts = append(acts, b.Restart)
	}
	em.Actions = map[string]string{}
	for _, a := range acts {
		var ps []string
		for _, p := range m.Actions[a] {
			ps = append(ps, evalPrefix+"p_"+p.Name)
		}
		name := evalPrefix + "act_" + a
		if len(ps) == 0 {
			fmt.Fprintf(&w, "  action %s = %s\n", name, a)
		} else {
			fmt.Fprintf(&w, "  action %s(%s) = %s(%s)\n", name, strings.Join(ps, ", "), a, strings.Join(ps, ", "))
		}
		em.Actions[a] = name
	}
	w.WriteString("}\n")
	em.Text = w.String()
	return em, nil
}

// splitTemplate splits a template into its text and its fields: parts[i]
// is the text before holes[i], and parts has one more than holes. A hole
// is an action of the template ({{.obs.x}}, {{toList .F}}) that renders
// one value; anything else (if, range, with, a variable) cannot be a
// definition's parameter, and is an error.
// split caches splitTemplate's results, process-wide: a binding's expect
// splits the same for every call of every candidate.
var split sync.Map // process-wide: template text -> splitResult

type splitResult struct {
	parts, holes []string
	err          error
}

func splitCached(tpl string) (parts, holes []string, err error) {
	if v, ok := split.Load(tpl); ok {
		r := v.(splitResult)
		return r.parts, r.holes, r.err
	}
	parts, holes, err = splitTemplate(tpl)
	split.Store(tpl, splitResult{parts, holes, err})
	return parts, holes, err
}

func splitTemplate(tpl string) (parts, holes []string, err error) {
	trees, err := parse.Parse("t", tpl, "{{", "}}", map[string]any{"set": true, "toSet": true, "toList": true, "toMap": true, "toQuint": true,
		"max": true, "count": true, "procs": true, "add": true, "atLeast": true}) // the binding's functions, by name: parse checks only that they exist
	if err != nil {
		return nil, nil, err
	}
	var text strings.Builder
	for _, n := range trees["t"].Root.Nodes {
		switch x := n.(type) {
		case *parse.TextNode:
			text.Write(x.Text)
		case *parse.ActionNode:
			if len(x.Pipe.Decl) > 0 {
				return nil, nil, fmt.Errorf("%s declares a variable: the Go evaluator takes a template of text and fields", x)
			}
			parts = append(parts, text.String())
			text.Reset()
			holes = append(holes, x.String())
		default:
			return nil, nil, fmt.Errorf("%s: the Go evaluator takes a template of text and fields, not %T", n, n)
		}
	}
	parts = append(parts, text.String())
	// a field the text reads as part of a token (inside a string literal,
	// glued to a name or a number, applied or indexed) means something else
	// as a parameter: "n{{.id}}" is one string, n__gtg_h0 a name
	for i := range holes {
		before, after := parts[i], parts[i+1]
		if strings.Count(strings.Join(parts[:i+1], ""), `"`)%2 == 1 {
			return nil, nil, fmt.Errorf("%s is inside a string literal: the Go evaluator takes fields that are values of their own", holes[i])
		}
		// (a value followed by .f(), [i] or a call is applied the same way as
		// a parameter, but for a negative one: atomic, per call)
		if n := len(before); n > 0 && glues(before[n-1]) || len(after) > 0 && after[0] != '.' && glues(after[0]) {
			return nil, nil, fmt.Errorf("%s is glued to the text around it: the Go evaluator takes fields that are values of their own", holes[i])
		}
	}
	return parts, holes, nil
}

func glues(c byte) bool {
	return c == '_' || c == '"' || c == '.' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
}

// Atomic reports whether a field's value, rendered, reads as one value
// wherever the template puts it: a negative number before ^ (-3^2 is
// -(3^2) in Quint) does not, as a parameter it is (-3)^2.
func atomic(v, after string) bool {
	if !strings.HasPrefix(v, "-") {
		return true
	}
	a := strings.TrimLeft(after, " \t")
	return a == "" || !strings.ContainsRune("^.[(", rune(a[0]))
}

// An ObsComparison is a conjunct of an expect that compares a state
// variable with one observation: `balance == {{.obs.balance}}` is Var
// "balance", Field "balance".
type ObsComparison struct{ Var, Field string }

// ObsComparisons are the conjuncts of the expect template that compare a
// state variable with an observation, `v == {{.obs.f}}` at the top level
// of an `and` chain (outside brackets and string literals), in order: a
// state mismatch's observed fields that differ from the model's are
// those whose variable's value after the step is not the observation
// (qshrink.SameFailure). A template the Go evaluator cannot split (a
// range, a variable) has none.
func ObsComparisons(expect string) []ObsComparison {
	parts, holes, err := splitCached(expect)
	if err != nil {
		return nil
	}
	var out []ObsComparison
	depth, inStr := 0, false
	for i, h := range holes {
		// the text before the hole moves the depth: the hole is at the top
		// level only at depth 0
		for _, c := range parts[i] {
			switch {
			case c == '"':
				inStr = !inStr
			case inStr:
			case c == '(' || c == '{' || c == '[':
				depth++
			case c == ')' || c == '}' || c == ']':
				depth--
			}
		}
		field, ok := strings.CutPrefix(h, "{{.obs.")
		if !ok || depth != 0 || inStr {
			continue
		}
		field, ok = strings.CutSuffix(field, "}}")
		if !ok || !validIdent(field) {
			continue
		}
		before := strings.TrimRight(parts[i], " \t\n")
		lhs, ok := strings.CutSuffix(before, "==")
		if !ok {
			continue
		}
		lhs = strings.TrimRight(lhs, " \t\n")
		v := lhs[strings.LastIndexFunc(lhs, func(r rune) bool { return !identRune(r) })+1:]
		rest := strings.TrimRight(lhs[:len(lhs)-len(v)], " \t\n")
		after := strings.TrimLeft(parts[i+1], " \t\n")
		if !validIdent(v) || rest != "" && !strings.HasSuffix(rest, " and") && rest != "and" || after != "" && !strings.HasPrefix(after, "and ") && after != "and" {
			continue
		}
		out = append(out, ObsComparison{Var: v, Field: field})
	}
	return out
}

func identRune(r rune) bool {
	return r == '_' || r >= '0' && r <= '9' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z'
}

func validIdent(s string) bool {
	if s == "" || s[0] >= '0' && s[0] <= '9' {
		return false
	}
	for _, r := range s {
		if !identRune(r) {
			return false
		}
	}
	return true
}
