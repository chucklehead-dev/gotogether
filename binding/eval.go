package binding

import (
	"fmt"
	"path/filepath"
	"strings"
	"text/template/parse"
)

// An EvalModule is a Quint module through which a model is evaluated in
// Go (internal/qeval) instead of replayed by quint: it imports the model
// with its constants passed through (one compilation serves every
// instance), and holds a definition for each action's expect whose
// parameters are the template's fields. A step is then the model's
// action applied to its call's arguments, and its expect the definition
// applied to the call's ExpectArgs: the same Quint, with the step's
// values in place of the template's fields.
type EvalModule struct {
	Name string // the module's
	Text string // its source
	Init string // its init action (the model's)
	// Consts are the model's constants, each the name of the module's own
	// that passes it through
	Consts map[string]string
	// Actions are the model's actions, each the name of the module's that
	// applies it; Expects each action's expect, its definition's name
	Actions, Expects map[string]string
	// Invariants and Eventually are the binding's vals, each the name of
	// the module's val that reads it
	Invariants, Eventually map[string]string
}

// evalPrefix names what the module adds, apart from the model's names.
const evalPrefix = "__gtg_"

// EvalModule is the binding's evaluation module, written for qntPath (the
// model's import is relative to it). A binding whose templates the module
// cannot carry (a template that is more than text and fields, a constant
// whose type the model does not say) has none: the error says why.
func (b *Binding) EvalModule(m *Model, qntPath string) (*EvalModule, error) {
	em := &EvalModule{Name: evalPrefix + "eval", Init: evalPrefix + "init", Consts: map[string]string{},
		Expects: map[string]string{}, Invariants: map[string]string{}, Eventually: map[string]string{}}
	var w strings.Builder
	fmt.Fprintf(&w, "// Generated by gotogether for the Go evaluator: %s's model, its constants passed through.\n", filepath.Base(b.SpecPath()))
	fmt.Fprintf(&w, "module %s {\n", em.Name)
	var overrides []string
	for _, c := range sortedKeys(m.Consts) {
		name := evalPrefix + "c_" + c
		fmt.Fprintf(&w, "  const %s: %s\n", name, m.Consts[c])
		em.Consts[c] = name
		overrides = append(overrides, c+" = "+name)
	}
	rel, err := filepath.Rel(filepath.Dir(qntPath), b.SpecPath())
	if err != nil {
		return nil, err
	}
	rel = strings.TrimSuffix(filepath.ToSlash(rel), ".qnt")
	if len(overrides) > 0 {
		fmt.Fprintf(&w, "  import %s(%s).* from %q\n", b.Module, strings.Join(overrides, ", "), rel)
	} else {
		fmt.Fprintf(&w, "  import %s.* from %q\n", b.Module, rel)
	}
	if b.Defs != "" {
		w.WriteString(b.Defs + "\n")
	}
	for _, a := range sortedKeys(b.Actions) {
		ab := b.Actions[a]
		if ab.Expect == "" {
			continue
		}
		parts, holes, err := splitTemplate(ab.Expect)
		if err != nil {
			return nil, fmt.Errorf("action %s's expect: %w", a, err)
		}
		name := evalPrefix + "expect_" + a
		params := make([]string, len(holes))
		var body strings.Builder
		for i := range holes {
			params[i] = fmt.Sprintf("%sh%d", evalPrefix, i)
			body.WriteString(parts[i] + params[i])
		}
		body.WriteString(parts[len(holes)])
		sig := ""
		if len(params) > 0 {
			sig = "(" + strings.Join(params, ", ") + ")"
		}
		fmt.Fprintf(&w, "  def %s%s = %s\n", name, sig, body.String())
		em.Expects[a] = name
	}
	for i, inv := range b.Invariants {
		name := fmt.Sprintf("%sinv_%d", evalPrefix, i)
		fmt.Fprintf(&w, "  val %s = %s\n", name, inv)
		em.Invariants[inv] = name
	}
	for i, ev := range b.Eventually {
		name := fmt.Sprintf("%sev_%d", evalPrefix, i)
		fmt.Fprintf(&w, "  val %s = %s\n", name, ev)
		em.Eventually[ev] = name
	}
	fmt.Fprintf(&w, "  action %s = init\n", em.Init)
	// each action through a definition of the module's own: quint keeps
	// those, and what they reach, where it drops what init and step do not
	acts := sortedKeys(m.Actions)
	if _, ok := m.Actions[b.Restart]; b.Restart != "" && !ok {
		acts = append(acts, b.Restart)
	}
	em.Actions = map[string]string{}
	for _, a := range acts {
		var ps []string
		for _, p := range m.Actions[a] {
			ps = append(ps, evalPrefix+"p_"+p.Name)
		}
		name := evalPrefix + "act_" + a
		if len(ps) == 0 {
			fmt.Fprintf(&w, "  action %s = %s\n", name, a)
		} else {
			fmt.Fprintf(&w, "  action %s(%s) = %s(%s)\n", name, strings.Join(ps, ", "), a, strings.Join(ps, ", "))
		}
		em.Actions[a] = name
	}
	w.WriteString("}\n")
	em.Text = w.String()
	return em, nil
}

// splitTemplate splits a template into its text and its fields: parts[i]
// is the text before holes[i], and parts has one more than holes. A hole
// is an action of the template ({{.obs.x}}, {{toList .F}}) that renders
// one value; anything else (if, range, with, a variable) cannot be a
// definition's parameter, and is an error.
func splitTemplate(tpl string) (parts, holes []string, err error) {
	trees, err := parse.Parse("t", tpl, "{{", "}}", map[string]any{"set": true, "toSet": true, "toList": true, "toMap": true,
		"max": true, "count": true, "procs": true, "add": true, "atLeast": true}) // the binding's functions, by name: parse checks only that they exist
	if err != nil {
		return nil, nil, err
	}
	var text strings.Builder
	for _, n := range trees["t"].Root.Nodes {
		switch x := n.(type) {
		case *parse.TextNode:
			text.Write(x.Text)
		case *parse.ActionNode:
			if len(x.Pipe.Decl) > 0 {
				return nil, nil, fmt.Errorf("%s declares a variable: the Go evaluator takes a template of text and fields", x)
			}
			parts = append(parts, text.String())
			text.Reset()
			holes = append(holes, x.String())
		default:
			return nil, nil, fmt.Errorf("%s: the Go evaluator takes a template of text and fields, not %T", n, n)
		}
	}
	parts = append(parts, text.String())
	return parts, holes, nil
}
